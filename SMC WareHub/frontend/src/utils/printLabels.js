export function splitLines(text) {
  return (text || '').split('\n').filter(Boolean);
}

export function parseBoldSegments(text) {
  return (text || '').split(/\*\*(.*?)\*\*/g).map((segment, index) => ({ text: segment, bold: index % 2 === 1 }));
}

